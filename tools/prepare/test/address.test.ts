import { describe, expect, it } from 'vitest'
import { addressQueries, parseAddress, streetForms } from '../src/address'

describe('parseAddress', () => {
  it.each([
    [
      'Город Москва, пр-кт.Волгоградский, д. 128 к 5',
      'Москва',
      null,
      'Волгоградский проспект',
      '128 к5',
    ],
    [
      'г.Город Москва, б-р.Самаркандский, д. 32к1',
      'Москва',
      null,
      'Самаркандский бульвар',
      '32 к1',
    ],
    [
      'Город Москва, ул.Международная, д. 28 стр. 1',
      'Москва',
      null,
      'Международная улица',
      '28 с1',
    ],
    [
      'Город Москва, ул.Земляной Вал, д. 24/30 стр. 1',
      'Москва',
      null,
      'Земляной Вал улица',
      '24/30 с1',
    ],
    [
      'г.Город Москва, наб.Семеновская, д. 3/1к2',
      'Москва',
      null,
      'Семеновская набережная',
      '3/1 к2',
    ],
    ['Москва, проезд Орехово-Зуевский, д. 18/8', 'Москва', null, 'Орехово-Зуевский проезд', '18/8'],
    ['Домодедово, проезд.Советский 1-й, д. 1А', 'Домодедово', null, '1-й Советский проезд', '1А'],
    ['Кашира, ул.8 Марта, д. 22', 'Кашира', null, '8 Марта улица', '22'],
    ['МО, г. Кашира Кржижановского ул. д. 7к2', 'Кашира', null, 'Кржижановского улица', '7 к2'],
    ['МО, г. Ступино Андропова ул. д. 33', 'Ступино', null, 'Андропова улица', '33'],
    ['Москва Булатниковский пр-зд. д. 6к1', 'Москва', null, 'Булатниковский проезд', '6 к1'],
    ['Москва Бирюлевская ул. д. 44', 'Москва', null, 'Бирюлевская улица', '44'],
    ['г. Москва, ул Юных Ленинцев, д 83с 4', 'Москва', null, 'Юных Ленинцев улица', '83 с4'],
    ['г.Москва проезд Симферопольский, д.7', 'Москва', null, 'Симферопольский проезд', '7'],
    ['Город Москва, ш.Каширское, д. 136', 'Москва', null, 'Каширское шоссе', '136'],
    [
      'Город Москва, пр-кт.60-летия Октября, д. 18 к 2',
      'Москва',
      null,
      '60-летия Октября проспект',
      '18 к2',
    ],
    [
      'обл.Московская область, г.Домодедово, пгт.Востряково-1, ул.Жуковского, д. 14/18',
      'Домодедово',
      'Востряково-1',
      'Жуковского улица',
      '14/18',
    ],
    [
      'Город Москва, б-р.Самаркандский Квартал 137а, д. к5',
      'Москва',
      null,
      'Самаркандский бульвар',
      '137а к5',
    ],
  ])('%s', (raw, city, locality, street, house) => {
    const parsed = parseAddress(raw)
    expect(parsed).toMatchObject({ city, locality, house })
    expect(streetForms(parsed)[0]).toBe(street)
  })

  it('строит запросы от точного к грубому без повторов', () => {
    expect(addressQueries(parseAddress('Город Москва, ул.Земляной Вал, д. 24/30 стр. 1'))).toEqual([
      'Москва, Земляной Вал улица, 24/30 с1',
      'Москва, улица Земляной Вал, 24/30 с1',
      'Москва, Земляной Вал улица, 24/30',
      'Москва, улица Земляной Вал, 24/30',
      'Москва, Земляной Вал улица',
      'Москва, улица Земляной Вал',
    ])
    expect(addressQueries(parseAddress('Кашира, ул.Победы, д. 9'))).toEqual([
      'Кашира, Победы улица, 9',
      'Кашира, улица Победы, 9',
      'Кашира, Победы улица',
      'Кашира, улица Победы',
    ])
  })

  it('при населённом пункте пробует запросы и без него', () => {
    const queries = addressQueries(
      parseAddress(
        'обл.Московская область, г.Домодедово, пгт.Востряково-1, ул.Жуковского, д. 14/18',
      ),
    )
    expect(queries[0]).toBe('Домодедово, Востряково-1, Жуковского улица, 14/18')
    expect(queries).toContain('Домодедово, улица Жуковского, 14/18')
    expect(queries.indexOf('Домодедово, улица Жуковского, 14/18')).toBeLessThan(
      queries.indexOf('Домодедово, Востряково-1, Жуковского улица'),
    )
  })

  it('падает на адресе без города', () => {
    expect(() => parseAddress('ул.Победы, д. 9')).toThrow(/город/)
  })
})
